function mapPapel(cargo) {
  const c = (cargo || "").toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").trim();
  if (/vice.?presidente/.test(c)) return "vice-presidente";
  if (/presidente/.test(c)) return "presidente";
  if (/secretari/.test(c)) return "secretario";
  if (/tesourei/.test(c)) return "tesoureiro";
  if (/conselho.?fiscal/.test(c)) return "conselho-fiscal";
  if (/suplente/.test(c)) return "suplente";
  if (/diretor/.test(c)) return "diretor";
  return "outro";
}

