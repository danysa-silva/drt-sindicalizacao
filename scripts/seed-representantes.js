function normalizar(str) {
  return (str || "").toUpperCase().normalize("NFD").replace(/[̀-ͯ]/g, "").trim();
}

async function main() {
  let criados = 0, vinculados = 0, jaExistiam = 0, semSindicato = 0, erros = 0;

  // Busca todos sindicatos de uma vez (case insensitive via normalização)
  const { rows: sindicatosDB } = await pool.query(`SELECT id, nome FROM "Sindicato"`);
  const sindicatoMap = new Map();
  for (const s of sindicatosDB) {
    sindicatoMap.set(normalizar(s.nome), s.id);
  }

  for (const entrada of dados) {
    const nomePessoa = entrada.n.trim();
    const papel = mapPapel(entrada.c);
    const nomeNorm = normalizar(entrada.s);

    // Tenta match exato primeiro, depois parcial
    let sindicatoId = sindicatoMap.get(nomeNorm);
    if (!sindicatoId) {
      // busca parcial: pega o sindicato cujo nome normalizado contém as primeiras palavras
      const palavrasChave = nomeNorm.split(" ").slice(0, 5).join(" ");
      for (const [key, id] of sindicatoMap) {
        if (key.includes(palavrasChave) || palavrasChave.includes(key.split(" ").slice(0, 5).join(" "))) {
          sindicatoId = id;
          break;
        }
      }
    }

    if (!sindicatoId) {
      console.warn(`⚠ Sindicato não encontrado: ${entrada.s}`);
      semSindicato++;
      continue;
    }

    try {
      // Upsert representante por nome
      const repRes = await pool.query(
        `INSERT INTO "Representante" (nome, "createdAt", "updatedAt")
         VALUES ($1, NOW(), NOW())
         ON CONFLICT DO NOTHING
         RETURNING id`,
        [nomePessoa]
      );

      let representanteId;
      if (repRes.rows.length > 0) {
        representanteId = repRes.rows[0].id;
        criados++;
      } else {
        const existeRes = await pool.query(
          `SELECT id FROM "Representante" WHERE LOWER(nome) = LOWER($1) LIMIT 1`,
          [nomePessoa]
        );
        if (existeRes.rows.length === 0) {
          // nome duplicado mas sem conflito (sem unique constraint) — insere mesmo assim
          const insRes = await pool.query(
            `INSERT INTO "Representante" (nome, "createdAt", "updatedAt") VALUES ($1, NOW(), NOW()) RETURNING id`,
            [nomePessoa]
          );
          representanteId = insRes.rows[0].id;
          criados++;
        } else {
          representanteId = existeRes.rows[0].id;
          jaExistiam++;
        }
      }

      // Vincula ao sindicato se não existir
      const linkRes = await pool.query(
        `INSERT INTO "RepresentanteSindicato" ("representanteId", "sindicatoId", papel, "createdAt")
         VALUES ($1, $2, $3, NOW())
         ON CONFLICT ("representanteId", "sindicatoId", papel, "dataInicio") DO NOTHING
         RETURNING id`,
        [representanteId, sindicatoId, papel]
      );

      if (linkRes.rows.length > 0) {
        vinculados++;
        console.log(`+ ${nomePessoa} → ${papel} (${entrada.s.slice(0, 50)})`);
      } else {
        console.log(`= ${nomePessoa} → já vinculado`);
      }
    } catch (e) {
      erros++;
      console.error(`✗ ${nomePessoa}: ${e.message}`);
    }
  }

  console.log(`\n✅ Representantes criados: ${criados} | Já existiam: ${jaExistiam} | Vínculos adicionados: ${vinculados} | Sem sindicato: ${semSindicato} | Erros: ${erros}`);
  await pool.end();
}

main().catch((e) => { console.error(e); process.exit(1); });
